import React from 'react';
import {
  PortfolioRiskResponse,
  PortfolioRiskMetrics,
  getRiskTotalPeriodReturn,
  getRiskAnnualizedReturn,
  getRiskVolatility,
  getRiskDownsideVolatility,
  getRiskSharpeRatio,
  getRiskSortinoRatio,
  getRiskCalmarRatio,
  getRiskMaxDrawdown,
  getRiskDrawdownDuration,
  getRiskVaR95,
  getRiskCVaR95,
  getRiskCAGR,
} from '../../types/portfolio';
import { formatPercent, formatRatio, formatNumber } from '../../utils/formatters';
import {
  TrendingUp,
  Activity,
  Shield,
  AlertTriangle,
  Clock,
  Compass,
  Zap,
  HelpCircle,
  Flame,
} from 'lucide-react';

export interface RiskMetricCardsProps {
  riskData: PortfolioRiskResponse | PortfolioRiskMetrics | null;
  isLoading?: boolean;
}

interface MetricItem {
  id: string;
  label: string;
  category: 'returns' | 'ratios' | 'tail_risk' | 'volatility';
  value: number | null;
  format: 'percent' | 'ratio' | 'days';
  description: string;
  tooltip: string;
  icon: React.ComponentType<{ className?: string }>;
  tone: 'positive' | 'negative' | 'neutral' | 'accent';
}

export const RiskMetricCards: React.FC<RiskMetricCardsProps> = ({ riskData, isLoading = false }) => {
  // Extract values deterministically using safe accessors
  const totalReturn = getRiskTotalPeriodReturn(riskData);
  const annualizedReturn = getRiskAnnualizedReturn(riskData);
  const cagr = getRiskCAGR(riskData);
  const volatility = getRiskVolatility(riskData);
  const downsideVol = getRiskDownsideVolatility(riskData);
  const sharpe = getRiskSharpeRatio(riskData);
  const sortino = getRiskSortinoRatio(riskData);
  const calmar = getRiskCalmarRatio(riskData);
  const maxDrawdown = getRiskMaxDrawdown(riskData);
  const drawdownDuration = getRiskDrawdownDuration(riskData);
  const var95 = getRiskVaR95(riskData);
  const cvar95 = getRiskCVaR95(riskData);

  const metrics: MetricItem[] = [
    {
      id: 'metric-total-return',
      label: 'Total Period Return',
      category: 'returns',
      value: totalReturn,
      format: 'percent',
      description: 'Aggregate historical return across evaluated window',
      tooltip: 'Cumulative net profit or loss generated by the portfolio over the full calculation period.',
      icon: TrendingUp,
      tone: totalReturn !== null && totalReturn >= 0 ? 'positive' : 'negative',
    },
    {
      id: 'metric-annualized-return',
      label: 'Annualized Return',
      category: 'returns',
      value: annualizedReturn,
      format: 'percent',
      description: 'Geometric compound return scaled to 12 months',
      tooltip: 'The annualized rate of portfolio return assuming consistent compounding over 252 trading days.',
      icon: Compass,
      tone: annualizedReturn !== null && annualizedReturn >= 0 ? 'positive' : 'negative',
    },
    {
      id: 'metric-cagr',
      label: 'CAGR',
      category: 'returns',
      value: cagr,
      format: 'percent',
      description: 'Compound Annual Growth Rate',
      tooltip: 'Compound Annual Growth Rate representing the constant year-over-year rate of return smoothing volatility.',
      icon: Zap,
      tone: cagr !== null && cagr >= 0 ? 'positive' : 'negative',
    },
    {
      id: 'metric-volatility',
      label: 'Annualized Volatility (σ)',
      category: 'volatility',
      value: volatility,
      format: 'percent',
      description: 'Standard deviation of periodic asset returns',
      tooltip: 'Annualized sample standard deviation of historical returns. Reflects total portfolio price dispersion.',
      icon: Activity,
      tone: 'neutral',
    },
    {
      id: 'metric-downside-volatility',
      label: 'Downside Volatility (σd)',
      category: 'volatility',
      value: downsideVol,
      format: 'percent',
      description: 'Semi-deviation of negative returns below threshold',
      tooltip: 'Annualized standard deviation isolating only returns falling below the risk-free rate or minimum acceptable return.',
      icon: Activity,
      tone: 'neutral',
    },
    {
      id: 'metric-sharpe',
      label: 'Sharpe Ratio',
      category: 'ratios',
      value: sharpe,
      format: 'ratio',
      description: 'Excess return per unit of total volatility',
      tooltip: '(Portfolio Return - Risk Free Rate) / Total Volatility. Higher values (> 1.0) signify superior risk compensation.',
      icon: Shield,
      tone: sharpe !== null && sharpe >= 1.0 ? 'positive' : sharpe !== null && sharpe < 0 ? 'negative' : 'accent',
    },
    {
      id: 'metric-sortino',
      label: 'Sortino Ratio',
      category: 'ratios',
      value: sortino,
      format: 'ratio',
      description: 'Excess return penalized only by downside deviation',
      tooltip: '(Portfolio Return - Risk Free Rate) / Downside Volatility. Does not penalize upside volatility.',
      icon: Shield,
      tone: sortino !== null && sortino >= 1.2 ? 'positive' : 'accent',
    },
    {
      id: 'metric-calmar',
      label: 'Calmar Ratio',
      category: 'ratios',
      value: calmar,
      format: 'ratio',
      description: 'Annualized return divided by maximum drawdown',
      tooltip: 'Measures return generated relative to historical downside pain (Maximum Drawdown depth).',
      icon: Shield,
      tone: calmar !== null && calmar >= 1.0 ? 'positive' : 'accent',
    },
    {
      id: 'metric-max-drawdown',
      label: 'Maximum Drawdown',
      category: 'tail_risk',
      value: maxDrawdown,
      format: 'percent',
      description: 'Deepest peak-to-trough valuation contraction',
      tooltip: 'The largest historical percentage drop from an equity peak to a subsequent trough before a new peak was attained.',
      icon: Flame,
      tone: 'negative',
    },
    {
      id: 'metric-drawdown-duration',
      label: 'Drawdown Duration',
      category: 'tail_risk',
      value: drawdownDuration,
      format: 'days',
      description: 'Longest calendar interval spent below high-water mark',
      tooltip: 'Number of consecutive trading days required to recover previous peak portfolio equity value.',
      icon: Clock,
      tone: 'neutral',
    },
    {
      id: 'metric-var-95',
      label: 'Historical VaR (95%)',
      category: 'tail_risk',
      value: var95,
      format: 'percent',
      description: 'Value at Risk: 95th percentile expected loss boundary',
      tooltip: 'With 95% confidence, daily or periodic loss is not expected to exceed this threshold under standard conditions.',
      icon: AlertTriangle,
      tone: 'negative',
    },
    {
      id: 'metric-cvar-95',
      label: 'CVaR / Expected Shortfall (95%)',
      category: 'tail_risk',
      value: cvar95,
      format: 'percent',
      description: 'Average expected loss in the worst 5% of tail outcomes',
      tooltip: 'Conditional Value at Risk (Expected Shortfall): the expected loss when returns breach the 95% VaR threshold.',
      icon: AlertTriangle,
      tone: 'negative',
    },
  ];

  const formatValue = (metric: MetricItem): string => {
    if (metric.value === null || metric.value === undefined) {
      return '—';
    }
    if (metric.format === 'percent') {
      return formatPercent(metric.value, false, 2);
    }
    if (metric.format === 'ratio') {
      return formatRatio(metric.value, 2);
    }
    if (metric.format === 'days') {
      return `${formatNumber(metric.value, 0)} days`;
    }
    return String(metric.value);
  };

  const getToneStyle = (tone: MetricItem['tone'], isUnavailable: boolean) => {
    if (isUnavailable) {
      return {
        text: 'text-slate-400',
        badge: 'bg-slate-800/60 text-slate-400 border-slate-700/50',
      };
    }
    switch (tone) {
      case 'positive':
        return {
          text: 'text-emerald-400',
          badge: 'bg-emerald-500/10 text-emerald-400 border-emerald-500/20',
        };
      case 'negative':
        return {
          text: 'text-rose-400',
          badge: 'bg-rose-500/10 text-rose-400 border-rose-500/20',
        };
      case 'accent':
        return {
          text: 'text-cyan-400',
          badge: 'bg-cyan-500/10 text-cyan-400 border-cyan-500/20',
        };
      case 'neutral':
      default:
        return {
          text: 'text-slate-100',
          badge: 'bg-slate-800 text-slate-300 border-slate-700',
        };
    }
  };

  if (isLoading) {
    return (
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-4">
        {Array.from({ length: 12 }).map((_, i) => (
          <div
            key={`risk-skeleton-${i}`}
            className="p-4 rounded-xl bg-slate-900/60 border border-slate-800/80 animate-pulse space-y-3"
          >
            <div className="flex items-center justify-between">
              <div className="h-4 w-28 bg-slate-800 rounded" />
              <div className="h-6 w-6 bg-slate-800 rounded-full" />
            </div>
            <div className="h-8 w-20 bg-slate-800 rounded" />
            <div className="h-3 w-40 bg-slate-800/60 rounded" />
          </div>
        ))}
      </div>
    );
  }

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between flex-wrap gap-2">
        <div className="flex items-center gap-2">
          <Shield className="w-4 h-4 text-cyan-400" />
          <h3 className="text-sm font-semibold uppercase tracking-wider text-slate-300">
            Historical Quantitative Risk Profile
          </h3>
        </div>
        <div className="flex items-center gap-1.5 text-[11px] font-mono text-slate-400 bg-slate-900 px-2.5 py-1 rounded-md border border-slate-800">
          <span className="w-1.5 h-1.5 rounded-full bg-cyan-400 animate-pulse" />
          Authoritative Backend Calculations
        </div>
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-4">
        {metrics.map((metric) => {
          const Icon = metric.icon;
          const isUnavailable = metric.value === null || metric.value === undefined;
          const toneStyle = getToneStyle(metric.tone, isUnavailable);

          return (
            <div
              key={metric.id}
              id={metric.id}
              className="p-4 rounded-xl bg-slate-900/70 border border-slate-800/80 hover:border-slate-700/80 transition-all flex flex-col justify-between group relative"
            >
              <div>
                <div className="flex items-start justify-between gap-2 mb-2">
                  <span className="text-xs font-medium text-slate-400 leading-tight">
                    {metric.label}
                  </span>
                  <div
                    className="text-slate-500 hover:text-slate-300 transition-colors cursor-help shrink-0"
                    title={metric.tooltip}
                  >
                    <HelpCircle className="w-3.5 h-3.5" />
                  </div>
                </div>

                <div className="flex items-baseline gap-2 mb-1.5">
                  <span className={`text-2xl font-bold font-mono tracking-tight ${toneStyle.text}`}>
                    {formatValue(metric)}
                  </span>
                </div>
              </div>

              <div className="pt-2 border-t border-slate-800/60 mt-2 flex items-center justify-between">
                <span className="text-[11px] text-slate-400 truncate max-w-[200px]" title={metric.description}>
                  {metric.description}
                </span>
                <div className="p-1 rounded-md bg-slate-800/60 text-slate-400 shrink-0">
                  <Icon className="w-3 h-3" />
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
